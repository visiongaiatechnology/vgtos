 *
 * SPDX-License-Identifier: AGPL-3.0-or-later
 *
 * Reads the declared sRGB fallback tokens from glass-2100.css and computes the
 * contrast ratio of every text/control pair the console actually uses. OKLCH
 * tokens are tonally equivalent; the sRGB set is the guaranteed floor.
 *
 * This proves colour contrast only. It says nothing about pixels: browser
 * rendering is NOT_TESTED in this environment (headless browser unavailable).
 */

declare(strict_types=1);

require_once __DIR__ . '/lib/color-math.php';

$root = dirname(__DIR__, 2);
$cssPath = $root . '/src/UI/Dashboard/assets/glass-2100.css';
$docsDir = $root . '/docs/visual';
$css = (string) file_get_contents($cssPath);
$tokens = parse_css_tokens($css);

if ($tokens === []) {
    fwrite(STDERR, "No sRGB tokens found in glass-2100.css\n");
    exit(1);
}

$token = static function (string $name) use ($tokens): string {
    if (!isset($tokens[$name])) {
        throw new RuntimeException('Unknown token: ' . $name);
    }

    return $tokens[$name]['hex'];
};

$canvas = $token('canvas');
$canvas2 = $token('canvas-2');
$bg0 = $token('bg-0');
$glass1OverBg0 = blend($token('glass-1'), (float) $tokens['glass-1']['alpha'], $bg0);
$dialogBg = '#0d1419';
$quietBtn = blend($token('titanium'), 0.07, $canvas);
$warnTint = blend($token('warning'), 0.11, $canvas);
$successTint = blend($token('success'), 0.11, $canvas);
$dangerTint = blend($token('danger'), 0.11, $canvas);
$accentTint = blend($token('accent'), 0.10, $canvas);
$neutralTint = blend($token('titanium'), 0.09, $canvas);

/** @var list<array{0: string, 1: string, 2: string, 3: float, 4: string}> $pairs */
$pairs = [
    ['Primary text on content canvas', $token('text'), $canvas, 4.5, 'body, headings, row values'],
    ['Primary text on environment', $token('text'), $bg0, 4.5, 'console plane edge'],
    ['Secondary text on canvas', $token('text-2'), $canvas, 4.5, 'lede, hints, diagnostics values'],
    ['Muted text on canvas', $token('muted'), $canvas, 4.5, 'labels, timestamps, footnotes'],
    ['Muted text on environment', $token('muted'), $bg0, 4.5, 'eyebrows on Z0'],
    ['Muted text on inset panel', $token('muted'), $canvas2, 4.5, 'banner / notice detail'],
    ['Accent text on canvas', $token('accent'), $canvas, 4.5, 'version chip, info pill, links'],
    ['Accent strong on canvas', $token('accent-strong'), $canvas, 4.5, 'gradient edge'],
    ['Success text on canvas', $token('success'), $canvas, 4.5, 'mounted state'],
    ['Warning text on canvas', $token('warning'), $canvas, 4.5, 'safe mode, optional policy'],
    ['Critical text on canvas', $token('danger'), $canvas, 4.5, 'failed mount, destructive action'],
    ['Focus indicator on canvas', $token('focus'), $canvas, 3.0, 'non-text focus ring (1.4.11)'],
    ['Text on Z2 glass', $token('text'), $glass1OverBg0, 4.5, 'deploy rail composite'],
    ['Secondary text on Z2 glass', $token('text-2'), $glass1OverBg0, 4.5, 'deploy rail composite'],
    ['Muted text on Z2 glass', $token('muted'), $glass1OverBg0, 4.5, 'deploy rail composite'],
    ['Accent on Z2 glass', $token('accent'), $glass1OverBg0, 4.5, 'deploy rail composite'],
    ['Primary button label', $token('ink'), $token('accent'), 4.5, 'gradient start'],
    ['Primary button label (end)', $token('ink'), $token('accent-strong'), 4.5, 'gradient end'],
    ['Quiet button label', $token('text'), $quietBtn, 4.5, 'subtle button surface'],
    ['Danger button label (top)', '#1b0807', '#ec958e', 4.5, 'destructive confirm'],
    ['Danger button label (bottom)', '#1b0807', '#d8776f', 4.5, 'destructive confirm'],
    ['Warning pill text', $token('warning'), $warnTint, 4.5, 'status pill'],
    ['Success pill text', $token('success'), $successTint, 4.5, 'status pill'],
    ['Critical pill text', $token('danger'), $dangerTint, 4.5, 'status pill'],
    ['Info pill text', $token('accent'), $accentTint, 4.5, 'status pill'],
    ['Neutral pill text', $token('titanium'), $neutralTint, 4.5, 'status pill'],
    ['Dialog text on Z4 surface', $token('text'), $dialogBg, 4.5, 'modal body'],
    ['Dialog muted text on Z4 surface', $token('muted'), $dialogBg, 4.5, 'modal meta'],
    ['Dialog critical eyebrow on Z4', $token('danger'), $dialogBg, 4.5, 'destructive eyebrow'],
];

$rows = [];
$failures = 0;

foreach ($pairs as [$label, $fg, $bg, $min, $usage]) {
    $ratio = contrast_ratio($fg, $bg);
    $pass = $ratio + 0.0001 >= $min;
    if (!$pass) {
        $failures++;
    }
    $rows[] = ['label' => $label, 'fg' => $fg, 'bg' => $bg, 'ratio' => $ratio, 'min' => $min, 'usage' => $usage, 'pass' => $pass];
}

$md = "# GeDefense WPR â€” static contrast audit (WCAG 2.2 AA)\n\n";
$md .= "Generated by `tests/visual/audit-contrast.php` from the declared sRGB fallback tokens in\n";
$md .= "`src/UI/Dashboard/assets/glass-2100.css`. Ratios use the WCAG 2.x relative-luminance formula on\n";
$md .= "composited sRGB values; the OKLCH token set is tonally equivalent and used only where supported.\n\n";
$md .= "| # | Pair | Foreground | Background | Ratio | Requirement | Usage | Result |\n";
$md .= "|---|------|-----------|------------|-------|-------------|-------|--------|\n";

$i = 0;
foreach ($rows as $row) {
    $i++;
    $md .= sprintf(
        "| %d | %s | `%s` | `%s` | %.2f:1 | >= %.1f:1 | %s | %s |\n",
        $i,
        $row['label'],
        $row['fg'],
        $row['bg'],
        $row['ratio'],
        $row['min'],
        $row['usage'],
        $row['pass'] ? 'PASS' : 'FAIL'
    );
}

$md .= "\nNormal-text pairs require 4.5:1 (WCAG 1.4.3); the focus indicator is non-text and requires 3:1 (WCAG 1.4.11).\n";
$md .= "Pairs: **" . count($rows) . "**, failures: **" . $failures . "**.\n";
$md .= "Real browser paint and OKLCH wide-gamut rendering: NOT_TESTED (headless browser unavailable).\n";

if (file_put_contents($docsDir . '/contrast-audit.md', $md) === false) {
    fwrite(STDERR, "cannot write contrast audit\n");
    exit(1);
}

printf("contrast pairs: %d, failures: %d\n", count($rows), $failures);
exit($failures === 0 ? 0 : 1);
