declare(strict_types=1);

namespace VGT\Omega\System\Deployment;

/**
 * Generates the mu-plugin kernel that loads the GeDefense WPR runtime as a layer-0
 * MU plugin, before regular plugins are loaded.
 *
 * The payload is deterministic for a given plugin path and version, so the
 * deployer can compare SHA-256 hashes instead of rewriting an unchanged file.
 * The plugin path is embedded with var_export(): an installation path that
 * contains quotes, backslashes or newline bytes becomes a safe PHP string
 * literal instead of injected code. The generated file must pass `php -l` and
 * is designed to be idempotent when loaded twice.
 */
final class MuKernelPayload
{
    public const FILENAME = 'vgt-omega-kernel.php';

    public const DEFAULT_VERSION = '4.2.3';

    private const VERSION_PATTERN = '/^[0-9]{1,3}(\.[0-9]{1,3}){1,3}(-[A-Za-z0-9.]+)?$/';

    private const MAX_PLUGIN_PATH_LENGTH = 4096;

    private const TEMPLATE = <<<'VGT_KERNEL'
<?php
/**
 * Plugin Name: GeDefense WPR Layer-0 Kernel
 * Plugin URI: https://visiongaiatechnology.de
 * Description: AUTO-GENERATED layer-0 loader for the GeDefense WPR encrypted artifact runtime. Do not edit manually.
 * Version: __VGT_VERSION__
 * Requires at least: 6.0
 * Requires PHP: 8.1
 * Author: VisionGaia Technology
 * Author URI: https://visiongaiatechnology.de
 * License: AGPL-3.0-or-later
 * License URI: https://www.gnu.org/licenses/agpl-3.0.html
 * SPDX-License-Identifier: AGPL-3.0-or-later
 *
 * Copyright (C) 2026 VisionGaiaTechnology
 *
 * This program is free software: you can redistribute it and/or modify it under
 * the terms of the GNU Affero General Public License as published by the Free
 * Software Foundation, either version 3 of the License, or (at your option) any
 * later version. See the LICENSE file for the complete license text.
 *
 * This file is generated by VGT\Omega\System\Deployment\MuKernelPayload.
 * It is rewritten atomically only when the payload hash changes.
 *
 * @package VGT\Omega
 */

declare(strict_types=1);

if (!defined('ABSPATH')) {
    exit('VGT_ACCESS_DENIED');
}

if (defined('VGT_OMEGA_MU_KERNEL')) {
    return;
}

define('VGT_OMEGA_MU_KERNEL', true);
define('VGT_OMEGA_LAYER_ZERO', true);
define('VGT_OMEGA_KERNEL_VERSION', __VGT_VERSION_LITERAL__);

$vgt_omega_plugin_file = __VGT_PLUGIN_PATH_LITERAL__;

if (is_file($vgt_omega_plugin_file)) {
    require_once $vgt_omega_plugin_file;
} else {
    error_log('[VGT][LAYER0] GeDefense WPR plugin bootstrap file is missing.');
}
VGT_KERNEL;

    /** Token used as version literal placeholder in TEMPLATE. */
    private const TOKEN_VERSION = '__VGT_VERSION__';

    /** Token used as quoted version literal placeholder in TEMPLATE. */
    private const TOKEN_VERSION_LITERAL = '__VGT_VERSION_LITERAL__';

    /** Token used as quoted plugin path literal placeholder in TEMPLATE. */
    private const TOKEN_PLUGIN_PATH_LITERAL = '__VGT_PLUGIN_PATH_LITERAL__';

    /**
     * Build the complete kernel file source.
     *
     * @param string $pluginFile absolute path of the main GeDefense WPR plugin file
     * @param string $version    plugin version, e.g. 4.2.3
     *
     * @throws \InvalidArgumentException when path or version are malformed
     */
    public static function build(string $pluginFile, string $version): string
    {
        $pluginFile = trim($pluginFile);

        if ($pluginFile === ''
            || strlen($pluginFile) > self::MAX_PLUGIN_PATH_LENGTH
            || str_contains($pluginFile, "\0")
            || preg_match('/[\x00-\x1F\x7F]/', $pluginFile) === 1) {
            throw new \InvalidArgumentException('VGT MU kernel: the plugin file path is malformed.');
        }

        $version = trim($version);

        if (preg_match(self::VERSION_PATTERN, $version) !== 1) {
            throw new \InvalidArgumentException('VGT MU kernel: the version string is malformed.');
        }

        $payload = strtr(self::TEMPLATE, [
            self::TOKEN_VERSION => $version,
            self::TOKEN_VERSION_LITERAL => var_export($version, true),
            self::TOKEN_PLUGIN_PATH_LITERAL => var_export(str_replace('\\', '/', $pluginFile), true),
        ]);

        return $payload . "\n";
    }
}
